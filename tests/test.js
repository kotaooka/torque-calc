'use strict';
const T = require('../js/torque.js');
let fail = 0, n = 0;
function ok(name, cond, info = '') { n++; if (!cond) { fail++; console.log(`✕ ${name} ${info}`); } }
function eq(name, got, want, tol) { ok(name, Math.abs(got - want) <= tol, `: ${got} ≠ ${want}`); }

// ---- 応力断面積（ISO 898-1 の表 [mm²]） ----
const AS = { 3: 5.03, 4: 8.78, 5: 14.2, 6: 20.1, 8: 36.6, 10: 58.0, 12: 84.3, 14: 115, 16: 157, 18: 192, 20: 245, 22: 303, 24: 353, 27: 459, 30: 561, 33: 694, 36: 817, 39: 976 };
for (const d of Object.keys(AS)) {
  const g = T.threadGeom(+d, T.SIZES[d].P), w = AS[d];
  eq(`M${d} 応力断面積`, g.AS, w, w < 100 ? 0.06 : 0.6);
}
{ const g = T.threadGeom(10, 1.25); eq('M10×1.25 応力断面積（ISO 898-1 は 61.2）', g.AS, 61.2, 0.06); }

// ---- 公表トルク表との照合 ----
